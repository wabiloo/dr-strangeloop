"""Version stamp and the choices/constants shared by the playlist and manifest builders."""

from __future__ import annotations

from pathlib import Path


def _read_generator_version() -> str:
    """loop-dee-loop's own version (pyproject.toml's [project].version), for
    the "generated by" comment stamped into every manifest. Falls back to
    "unknown" where pyproject.toml isn't shipped next to serve.py (one directory above this package)."""
    import tomllib

    try:
        with open(Path(__file__).resolve().parents[1] / "pyproject.toml", "rb") as fh:
            return tomllib.load(fh)["project"]["version"]
    except (OSError, KeyError, tomllib.TOMLDecodeError):
        return "unknown"


GENERATOR_VERSION = _read_generator_version()
